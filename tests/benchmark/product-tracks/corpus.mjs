const makeTrack = ({
  key,
  productId,
  title,
  objectType = 't-shirt',
  brand = '',
  model = null,
  text = [],
  color = 'black',
  features = [],
  shape = ['short sleeve oversized tee'],
}) => {
  const mapping = {
    platform: 'youtube',
    content_ref: 'youtube:frozen-vpm',
    scope: 'time_window',
    timestamp_start_ms: 1000,
    timestamp_end_ms: 9000,
    object_type: objectType,
    brand,
    product_id: productId,
    title,
    destination: `https://example.com/${productId}`,
    provider: 'fixture',
    canonical_key: key,
    track_id: key,
    provenance: 'admin_verified',
  };
  const identity = {
    canonical_key: key,
    title,
    brand: brand || null,
    model,
    object_type: objectType,
    visible_text: text,
    color,
    material: 'cotton',
    style_attributes: ['oversized'],
    logos_markings: text,
    distinctive_features: features,
    shape_silhouette: shape,
    normalized_fingerprint: key,
    relationship: 'EXACT',
    provenance: 'admin_verified',
    verified_at: '2026-09-27T00:00:00.000Z',
    merchant_refs: [],
  };
  return { mapping, identity };
};

